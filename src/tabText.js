let hooked = false;
/** Dodaj TAB tekstove u jezike (jednom; i kad se jezik promeni ili engleski učita kasnije). */
export function useTabTexts() {
  Object.assign(LANGS.sr, sr);
  if (LANGS.en) Object.assign(LANGS.en, en);
  if (!hooked) { hooked = true; onLangChange(() => { Object.assign(LANGS.sr, sr); if (LANGS.en) Object.assign(LANGS.en, en); }); }
}
useTabTexts();
