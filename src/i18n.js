export const LANGS = { sr, en: null };
// Engleski se učitava po potrebi
let enLoading = null;
export function loadLang(l) {
  if (l !== 'en' || LANGS.en) return Promise.resolve();
  return (enLoading ||= import('./i18n-en.js').then((m) => { LANGS.en = m.default; }));
}
const LS_KEY = 'gitara-lang';

function initialLang() {
  try {
    const v = typeof localStorage !== 'undefined' && localStorage.getItem(LS_KEY);
    if (v === 'sr' || v === 'en') return v;
  } catch {}
  return 'sr';
}

let lang = initialLang();
const listeners = new Set();
/** Spremno kada je učitan izabrani jezik (main.js čeka pre prvog prikaza). */
export const i18nReady = loadLang(lang).catch(() => { lang = 'sr'; });

export const getLang = () => lang;

/** Prevod po ključu, sa zamenom {param}. Ako prevod ne postoji, koristi srpski. */
export function t(key, params) {
  let s = (LANGS[lang] && LANGS[lang][key]) ?? sr[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  return s;
}

/** Množina za „pesma“ (sr: 1 pesma, 2–4 pesme, 5+ pesama; en: song/songs). */
export function songsCount(n) {
  if (lang === 'en') return `${n} ${n === 1 ? 'song' : 'songs'}`;
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${n} pesma`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} pesme`;
  return `${n} pesama`;
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

/** Menja jezik odmah (bez ponovnog učitavanja). save: upiši i u IndexedDB (rezervna kopija). */
export async function setLang(next, { save = true } = {}) {
  if (next !== 'sr' && next !== 'en') return;
  await loadLang(next);
  const changed = next !== lang;
  lang = next;
  try { localStorage.setItem(LS_KEY, next); } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = next === 'en' ? 'en' : 'sr-Latn';
  if (save) {
    const { settings } = await import('./db.js');
    await settings.set('lang', next);
  }
  if (changed) listeners.forEach((fn) => { try { fn(next); } catch {} });
}
