export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

/** Menja jezik odmah (bez ponovnog učitavanja). save: upiši i u IndexedDB (rezervna kopija). */
export async function setLang(next, { save = true } = {}) {
  if (next !== 'sr' && next !== 'en') return;
  await loadLang(next);
  const changed = next !== lang;
  lang = next;
  try { localStorage.setItem(LS_KEY, next); } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = next === 'en' ? 'en' : 'sr-Latn';
  if (save) {
    const { settings } = await import('./db.js');
    await settings.set('lang', next);
  }
  if (changed) listeners.forEach((fn) => { try { fn(next); } catch {} });
}
